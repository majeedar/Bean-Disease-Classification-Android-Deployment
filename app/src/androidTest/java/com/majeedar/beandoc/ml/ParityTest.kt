package com.majeedar.beandoc.ml

import android.net.Uri
import android.util.Log
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.majeedar.beandoc.ml.ImageLoader.Companion.toPixels
import kotlinx.coroutines.runBlocking
import org.json.JSONObject
import org.junit.AfterClass
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.BeforeClass
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.nio.ByteBuffer
import kotlin.math.abs

/**
 * Proves the Android pipeline matches Python (AGENTS.md section 8.2).
 * Data: app/src/androidTest/assets/parity, generated by tools/make_parity_set.py.
 *
 * Two levels:
 * - Model input (strict): the preprocessed tensor must equal Python's. This is what the app controls.
 * - Prediction (looser): same label, probabilities within [PROB_TOLERANCE]. The dynamic-range
 *   quantized model gives slightly different outputs on different runtimes even for identical
 *   input (TF 2.17 Python with vs without XNNPACK differs by up to 0.09), so ±0.02 is not reachable.
 */
@RunWith(AndroidJUnit4::class)
class ParityTest {

    companion object {
        private const val TAG = "ParityTest"
        private const val PARITY_DIR = "parity"
        private const val INPUT_TOLERANCE = 0.01f
        private const val PROB_TOLERANCE = 0.10f

        private lateinit var classifier: BeanClassifier

        @BeforeClass
        @JvmStatic
        fun setUp() {
            classifier = BeanClassifier.create(InstrumentationRegistry.getInstrumentation().targetContext)
        }

        @AfterClass
        @JvmStatic
        fun tearDown() {
            classifier.close()
        }
    }

    private val testContext = InstrumentationRegistry.getInstrumentation().context
    private val targetContext = InstrumentationRegistry.getInstrumentation().targetContext

    private fun expected(): JSONObject =
        testContext.assets.open("$PARITY_DIR/expected.json").bufferedReader().use { JSONObject(it.readText()) }

    @Test
    fun labelsMatchPython() {
        val labels = expected().getJSONArray("labels")
        assertEquals((0 until labels.length()).map { labels.getString(it) }, classifier.labels)
    }

    @Test
    fun inputsAndPredictionsMatchPython() = runBlocking {
        val json = expected()
        val images = json.getJSONObject("images")
        val stride = json.getInt("grid_stride")
        val loader = ImageLoader(targetContext.contentResolver)
        val failures = mutableListOf<String>()
        val table = StringBuilder(
            "\n%-64s %-18s %-18s %9s %9s\n".format("image", "python", "android", "max|dx|", "max|dp|")
        )

        assertTrue("expected.json has no images", images.length() > 0)
        for (name in images.keys()) {
            val entry = images.getJSONObject(name)

            // Go through a file Uri, exactly like gallery and camera photos do.
            val file = File(targetContext.cacheDir, name)
            testContext.assets.open("$PARITY_DIR/$name").use { input ->
                file.outputStream().use { input.copyTo(it) }
            }
            val bitmap = loader.load(Uri.fromFile(file))
            val input = ImagePreprocessor.toInputBuffer(bitmap.toPixels(), bitmap.width)
            bitmap.recycle()
            file.delete()

            val inputDiff = maxGridDiff(input, entry.getJSONArray("input_grid").toFloats(), stride)
            val prediction = classifier.classify(input)

            val expectedPred = entry.getString("pred")
            val expectedProbs = entry.getJSONArray("probs").toFloats()
            val actualProbs = classifier.labels.map { prediction.probabilities.getValue(it) }
            val probDiff = expectedProbs.indices.maxOf { abs(expectedProbs[it] - actualProbs[it]) }

            table.append(
                "%-64s %-18s %-18s %9.4f %9.4f\n".format(name, expectedPred, prediction.label, inputDiff, probDiff)
            )
            if (inputDiff > INPUT_TOLERANCE) {
                failures += "$name: model input differs from python by $inputDiff (> $INPUT_TOLERANCE) - preprocessing bug"
            }
            if (prediction.label != expectedPred) {
                failures += "$name: label ${prediction.label} != python $expectedPred"
            }
            if (probDiff > PROB_TOLERANCE) {
                failures += "$name: probabilities $actualProbs differ from python " +
                    "${expectedProbs.toList()} by $probDiff (> $PROB_TOLERANCE)"
            }
        }

        table.lineSequence().forEach { Log.i(TAG, it) }
        assertTrue(failures.joinToString("\n", prefix = "Parity failures:\n"), failures.isEmpty())
    }

    /** Compares the NHWC float buffer with Python's values at every [stride]-th row and column. */
    private fun maxGridDiff(input: ByteBuffer, grid: FloatArray, stride: Int): Float {
        val size = ImagePreprocessor.INPUT_SIZE
        val floats = input.asFloatBuffer()
        var i = 0
        var max = 0f
        for (y in 0 until size step stride) {
            for (x in 0 until size step stride) {
                for (c in 0 until 3) {
                    max = maxOf(max, abs(floats.get((y * size + x) * 3 + c) - grid[i++]))
                }
            }
        }
        check(i == grid.size) { "input_grid has ${grid.size} values, expected $i" }
        return max
    }

    private fun org.json.JSONArray.toFloats() = FloatArray(length()) { getDouble(it).toFloat() }
}
